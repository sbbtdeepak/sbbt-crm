// Import route
files['App/api/cms/packages/import/route.ts'] = [
  'import { NextResponse } from "next/server";',
  'import { createClient } from "@/lib/supabase/server";',
  'import { DEFAULT_SITE_ID } from "@/app/dashboard/cms/types";',
  'import { parseExcelBuffer } from "@/lib/import/Parser";',
  'import { validateRows } from "@/lib/import/Validator";',
  'import {',
  '  PACKAGE_COLUMNS,',
  '  PACKAGE_IDENTITY_FIELDS,',
  '  PACKAGE_IMPORT_MODULE,',
  '} from "@/lib/import/package-columns";',
  'import { logImport } from "@/lib/import/Utils";',
  '',
  'export const dynamic = "force-dynamic";',
  '',
  'export async function POST(request: Request) {',
  '  try {',
  '    const formData = await request.formData();',
  '    const file = formData.get("file") as File | null;',
  '',
  '    if (!file) {',
  '      return NextResponse.json({ error: "No file provided" }, { status: 400 });',
  '    }',
  '',
  '    const buffer = Buffer.from(await file.arrayBuffer());',
  '',
  '    // Parse Excel',
  '    const parsed = await parseExcelBuffer(buffer, PACKAGE_COLUMNS);',
  '    if (!parsed.success) {',
  '      return NextResponse.json(',
  '        { error: "Parse failed", errors: parsed.errors || ["Failed to parse Excel file."] },',
  '        { status: 400 }',
  '      );',
  '    }',
  '',
  '    // Validate rows',
  '    const validation = await validateRows(parsed.rows, PACKAGE_COLUMNS, {',
  '      identityFields: PACKAGE_IDENTITY_FIELDS,',
  '    });',
  '',
  '    if (validation.errors.length > 0 && validation.validRows.length === 0) {',
  '      return NextResponse.json(',
  '        { error: "Validation failed", errors: validation.errors, warnings: validation.warnings },',
  '        { status: 400 }',
  '      );',
  '    }',
  '',
  '    const supabase = await createClient();',
  '    const validRows = validation.validRows;',
  '',
  '    let imported = 0;',
  '    let updated = 0;',
  '    const errors: string[] = [...validation.errors];',
  '    const warnings: string[] = [...validation.warnings];',
  '',
  '    // Group rows by package name',
  '    const packageMap = new Map<string, typeof validRows>();',
  '    for (const row of validRows) {',
  '      const pkgKey = String(row.package_name || "");',
  '      if (!pkgKey) continue;',
  '      if (!packageMap.has(pkgKey)) packageMap.set(pkgKey, []);',
  '      packageMap.get(pkgKey)!.push(row);',
  '    }',
  '',
  '    for (const [pkgName, rows] of packageMap) {',
  '      const firstRow = rows[0];',
  '      const slug =',
  '        String(firstRow.package_slug || "") ||',
  '        pkgName',
  '          .toLowerCase()',
  '          .replace(/\\s+/g, "-")',
  '          .replace(/[^a-z0-9-]/g, "");',
  '',
  '      // Check if exists by slug',
  '      const { data: existing } = await supabase',
  '        .from("cms_packages")',
  '        .select("id")',
  '        .eq("site_id", DEFAULT_SITE_ID)',
  '        .eq("slug", slug)',
  '        .maybeSingle();',
  '',
  '      let packageId: number;',
  '',
  '      if (existing) {',
  '        // Update',
  '        const { error: updateError } = await supabase',
  '          .from("cms_packages")',
  '          .update({',
  '            name: pkgName,',
  '            slug,',
  '            price: Number(firstRow.package_price) || 0,',
  '            description: String(firstRow.package_description || ""),',
  '            display_order: Number(firstRow.package_display_order) || 0,',
  '            is_active: String(firstRow.package_is_active).toLowerCase() !== "no",',
  '            updated_at: new Date().toISOString(),',
  '          })',
  '          .eq("id", existing.id);',
  '',
  '        if (updateError) {',
  '          errors.push(`Failed to update package "${pkgName}": ${updateError.message}`);',
  '          continue;',
  '        }',
  '        packageId = existing.id;',
  '        updated++;',
  '      } else {',
  '        // Insert',
  '        const { data: newPkg, error: insertError } = await supabase',
  '          .from("cms_packages")',
  '          .insert({',
  '            site_id: DEFAULT_SITE_ID,',
  '            name: pkgName,',
  '            slug,',
  '            price: Number(firstRow.package_price) || 0,',
  '            description: String(firstRow.package_description || ""),',
  '            display_order: Number(firstRow.package_display_order) || 0,',
  '            is_active: String(firstRow.package_is_active).toLowerCase() !== "no",',
  '          })',
  '          .select("id")',
  '          .single();',
  '',
  '        if (insertError || !newPkg) {',
  '          errors.push(`Failed to create package "${pkgName}": ${insertError?.message || "Unknown"}`);',
  '          continue;',
  '        }',
  '        packageId = newPkg.id;',
  '        imported++;',
  '      }',
  '',
  '      // Delete existing sections + items',
  '      const { data: existingSections } = await supabase',
  '        .from("cms_package_sections")',
  '        .select("id")',
  '        .eq("package_id", packageId);',
  '',
  '      if (existingSections && existingSections.length > 0) {',
  '        const sectionIds = existingSections.map((s: { id: number }) => s.id);',
  '        await supabase.from("cms_package_items").delete().in("section_id", sectionIds);',
  '        await supabase.from("cms_package_sections").delete().eq("package_id", packageId);',
  '      }',
  '',
  '      // Group rows by section',
  '      const sectionMap = new Map<string, typeof rows>();',
  '      for (const row of rows) {',
  '        const sectionTitle = String(row.section_title || "Default");',
  '        if (!sectionMap.has(sectionTitle)) sectionMap.set(sectionTitle, []);',
  '        sectionMap.get(sectionTitle)!.push(row);',
  '      }',
  '',
  '      // Insert sections + items',
  '      for (const [sectionTitle, sectionRows] of sectionMap) {',
  '        const firstSectionRow = sectionRows[0];',
  '        const { data: section, error: sectionError } = await supabase',
  '          .from("cms_package_sections")',
  '          .insert({',
  '            package_id: packageId,',
  '            title: sectionTitle,',
  '            display_order: Number(firstSectionRow.section_display_order) || 0,',
  '          })',
  '          .select("id")',
  '          .single();',
  '',
  '        if (sectionError || !section) {',
  '          warnings.push(`Failed to create section "${sectionTitle}": ${sectionError?.message || "Unknown"}`);',
  '          continue;',
  '        }',
  '',
  '        const items = sectionRows.map((row: Record<string, unknown>, idx: number) => ({',
  '          section_id: section.id,',
  '          item: String(row.item_name || ""),',
  '          brand: String(row.item_brand || ""),',
  '          specification: String(row.item_specification || ""),',
  '          remarks: String(row.item_remarks || ""),',
  '          display_order: Number(row.item_display_order) || idx + 1,',
  '        }));',
  '',
  '        const { error: itemsError } = await supabase.from("cms_package_items").insert(items);',
  '        if (itemsError) {',
  '          warnings.push(`Failed to insert items for "${sectionTitle}": ${itemsError.message}`);',
  '        }',
  '      }',
  '    }',
  '',
  '    // Log the import',
  '    await logImport({',
  '      module: PACKAGE_IMPORT_MODULE,',
  '      totalRows: validRows.length,',
  '      inserted: imported,',
  '      updated,',
  '      errors,',
  '      warnings,',
  '      status: errors.length === 0 ? "completed" : "completed_with_warnings",',
  '    });',
  '',
  '    return NextResponse.json({',
  '      success: true,',
  '      imported,',
  '      updated,',
  '      totalRows: validRows.length,',
  '      errors,',
  '      warnings,',
  '    });',
  '  } catch (err: unknown) {',
  '    const message = err instanceof Error ? err.message : "Import failed";',
  '    return NextResponse.json({ error: message }, { status: 500 });',
  '  }',
  '}',
  ''
].join('\n');

